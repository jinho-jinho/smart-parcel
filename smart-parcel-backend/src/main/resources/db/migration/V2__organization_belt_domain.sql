-- 4. 분류 시도: v1에서는 DECISION을 받을 때 생성
CREATE TABLE sorting_attempts (
    attempt_id               UUID PRIMARY KEY,
    organization_id          BIGINT       NOT NULL,
    belt_id                  BIGINT       NOT NULL,
    device_id                UUID         NOT NULL,
    rule_version_id          BIGINT       NOT NULL,
    captured_at              TIMESTAMPTZ  NOT NULL,
    decided_at               TIMESTAMPTZ  NOT NULL,
    decision_status          VARCHAR(12)  NOT NULL
                             CHECK (decision_status IN
                                    ('MATCHED', 'UNMATCHED', 'ERROR')),
    decision_error_code      VARCHAR(50),
    discharge_status         VARCHAR(12)  NOT NULL DEFAULT 'UNCONFIRMED'
                             CHECK (discharge_status IN
                                    ('UNCONFIRMED', 'CONFIRMED', 'FAILED')),
    discharge_at             TIMESTAMPTZ,
    discharge_conflict       BOOLEAN      NOT NULL DEFAULT FALSE,
    recognized_input_type    VARCHAR(10)
                             CHECK (recognized_input_type IN ('TEXT', 'COLOR')),
    recognized_value         VARCHAR(100),
    rule_id                  BIGINT,
    chute_id                 BIGINT,       -- 규칙이 지정한 목적 슈트
    observed_chute_id        BIGINT,       -- 센서로 확인한 경우에만 기록
    group_name_snapshot     VARCHAR(100) NOT NULL,
    item_name_snapshot      VARCHAR(100),
    chute_name_snapshot     VARCHAR(50),
    image_uri               TEXT,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),

    UNIQUE (organization_id, belt_id, device_id, attempt_id),
    FOREIGN KEY (organization_id, belt_id, device_id)
        REFERENCES devices (organization_id, belt_id, id),
    FOREIGN KEY (organization_id, belt_id, rule_version_id)
        REFERENCES rule_versions (organization_id, belt_id, id),
    FOREIGN KEY (
        organization_id, belt_id, rule_version_id, rule_id, chute_id
    )
        REFERENCES sorting_rules (
            organization_id, belt_id, version_id, id, chute_id
        ),
    FOREIGN KEY (organization_id, belt_id, observed_chute_id)
        REFERENCES chutes (organization_id, belt_id, id),

    CHECK (
        (recognized_input_type IS NULL AND recognized_value IS NULL)
        OR
        (recognized_input_type IS NOT NULL AND recognized_value IS NOT NULL)
    ),
    CHECK (
        (
            decision_status = 'MATCHED'
            AND rule_id IS NOT NULL
            AND chute_id IS NOT NULL
            AND recognized_input_type IS NOT NULL
            AND item_name_snapshot IS NOT NULL
            AND chute_name_snapshot IS NOT NULL
            AND decision_error_code IS NULL
        )
        OR
        (
            decision_status = 'UNMATCHED'
            AND rule_id IS NULL
            AND chute_id IS NULL
            AND item_name_snapshot IS NULL
            AND chute_name_snapshot IS NULL
            AND decision_error_code IS NULL
        )
        OR
        (
            decision_status = 'ERROR'
            AND rule_id IS NULL
            AND chute_id IS NULL
            AND item_name_snapshot IS NULL
            AND chute_name_snapshot IS NULL
            AND decision_error_code IS NOT NULL
        )
    ),
    CHECK (
        discharge_status = 'UNCONFIRMED'
        OR decision_status = 'MATCHED'
    ),
    CHECK (
        (
            discharge_status = 'UNCONFIRMED'
            AND discharge_at IS NULL
            AND observed_chute_id IS NULL
            AND discharge_conflict = FALSE
        )
        OR
        (
            discharge_status IN ('CONFIRMED', 'FAILED')
            AND discharge_at IS NOT NULL
        )
    )
);

-- 5. 장비가 보낸 개별 사건
CREATE TABLE device_events (
    event_id        UUID PRIMARY KEY,
    organization_id BIGINT      NOT NULL,
    belt_id         BIGINT      NOT NULL,
    device_id       UUID        NOT NULL,
    attempt_id      UUID,
    event_type      VARCHAR(24) NOT NULL
                    CHECK (event_type IN (
                        'DECISION',
                        'DISCHARGE_CONFIRMED',
                        'DISCHARGE_FAILED',
                        'DEVICE_ERROR'
                    )),
    error_code      VARCHAR(50),
    occurred_at     TIMESTAMPTZ NOT NULL,
    received_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    payload_sha256  CHAR(64)    NOT NULL
                    CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    image_sha256    CHAR(64)
                    CHECK (
                        image_sha256 IS NULL
                        OR image_sha256 ~ '^[0-9a-f]{64}$'
                    ),
    image_uri       TEXT,
    payload         JSONB       NOT NULL,

    UNIQUE (organization_id, event_id),
    FOREIGN KEY (organization_id, belt_id, device_id)
        REFERENCES devices (organization_id, belt_id, id),
    FOREIGN KEY (organization_id, belt_id, device_id, attempt_id)
        REFERENCES sorting_attempts
            (organization_id, belt_id, device_id, attempt_id),
    CHECK (
        (event_type = 'DECISION' AND attempt_id IS NOT NULL)
        OR
        (
            event_type = 'DISCHARGE_CONFIRMED'
            AND attempt_id IS NOT NULL
            AND error_code IS NULL
        )
        OR
        (
            event_type = 'DISCHARGE_FAILED'
            AND attempt_id IS NOT NULL
            AND error_code IS NOT NULL
        )
        OR
        (
            event_type = 'DEVICE_ERROR'
            AND error_code IS NOT NULL
        )
    )
);

CREATE UNIQUE INDEX uq_events_one_decision_per_attempt
    ON device_events (attempt_id)
    WHERE event_type = 'DECISION';

