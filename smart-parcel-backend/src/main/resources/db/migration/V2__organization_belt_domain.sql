-- 2. 벨트와 장비
CREATE TABLE conveyor_belts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id         BIGINT       NOT NULL REFERENCES organizations(id),
    code                    VARCHAR(40)  NOT NULL,
    name                    VARCHAR(100) NOT NULL,
    enabled                 BOOLEAN      NOT NULL DEFAULT TRUE,
    desired_rule_version_id BIGINT,
    desired_set_at          TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),

    UNIQUE (organization_id, code),
    UNIQUE (organization_id, id),
    CHECK (
        (desired_rule_version_id IS NULL AND desired_set_at IS NULL)
        OR
        (desired_rule_version_id IS NOT NULL AND desired_set_at IS NOT NULL)
    )
);

CREATE TABLE devices (
    id                      UUID PRIMARY KEY,
    organization_id         BIGINT       NOT NULL,
    belt_id                 BIGINT       NOT NULL,
    device_code             VARCHAR(80)  NOT NULL,
    credential_hash         VARCHAR(255) NOT NULL,
    active                  BOOLEAN      NOT NULL DEFAULT TRUE,
    credential_revoked      BOOLEAN      NOT NULL DEFAULT FALSE,
    applied_rule_version_id BIGINT,
    applied_at              TIMESTAMPTZ,
    last_seen_at            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),

    UNIQUE (organization_id, device_code),
    UNIQUE (organization_id, belt_id, id),
    FOREIGN KEY (organization_id, belt_id)
        REFERENCES conveyor_belts (organization_id, id),
    CHECK (
        (applied_rule_version_id IS NULL AND applied_at IS NULL)
        OR
        (applied_rule_version_id IS NOT NULL AND applied_at IS NOT NULL)
    )
);

-- 무결성을 위한 UNIQUE 인덱스: 벨트당 활성 장비 최대 1대
CREATE UNIQUE INDEX uq_devices_one_active_per_belt
    ON devices (organization_id, belt_id)
    WHERE active = TRUE;

-- 물리 슈트. 동작 각도는 아래 version_chutes에 버전별로 저장한다.
CREATE TABLE chutes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT      NOT NULL,
    belt_id         BIGINT      NOT NULL,
    code            VARCHAR(40) NOT NULL,
    name            VARCHAR(50) NOT NULL,
    enabled         BOOLEAN     NOT NULL DEFAULT TRUE,

    UNIQUE (organization_id, belt_id, code),
    UNIQUE (organization_id, belt_id, id),
    FOREIGN KEY (organization_id, belt_id)
        REFERENCES conveyor_belts (organization_id, id)
);

-- 3. 분류 그룹과 배포 설정
CREATE TABLE sorting_groups (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL,
    belt_id         BIGINT       NOT NULL,
    name            VARCHAR(100) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    UNIQUE (belt_id, name),
    UNIQUE (organization_id, belt_id, id),
    FOREIGN KEY (organization_id, belt_id)
        REFERENCES conveyor_belts (organization_id, id)
);

CREATE TABLE rule_versions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     BIGINT       NOT NULL,
    belt_id             BIGINT       NOT NULL,
    group_id            BIGINT       NOT NULL,
    group_name_snapshot VARCHAR(100) NOT NULL,
    version_no          INTEGER      NOT NULL CHECK (version_no > 0),
    status              VARCHAR(12)  NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT', 'PUBLISHED')),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at        TIMESTAMPTZ,

    UNIQUE (group_id, version_no),
    UNIQUE (organization_id, belt_id, id),
    FOREIGN KEY (organization_id, belt_id, group_id)
        REFERENCES sorting_groups (organization_id, belt_id, id),
    CHECK (
        (status = 'DRAFT' AND published_at IS NULL)
        OR
        (status = 'PUBLISHED' AND published_at IS NOT NULL)
    )
);

-- 해당 버전을 배포했을 때의 슈트 이름과 서보 각도
CREATE TABLE version_chutes (
    organization_id     BIGINT      NOT NULL,
    belt_id             BIGINT      NOT NULL,
    version_id          BIGINT      NOT NULL,
    chute_id            BIGINT      NOT NULL,
    chute_name_snapshot VARCHAR(50) NOT NULL,
    servo_deg_snapshot  SMALLINT    NOT NULL
                        CHECK (servo_deg_snapshot BETWEEN 0 AND 180),

    PRIMARY KEY (organization_id, belt_id, version_id, chute_id),
    FOREIGN KEY (organization_id, belt_id, version_id)
        REFERENCES rule_versions (organization_id, belt_id, id),
    FOREIGN KEY (organization_id, belt_id, chute_id)
        REFERENCES chutes (organization_id, belt_id, id)
);

CREATE TABLE sorting_rules (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL,
    belt_id         BIGINT       NOT NULL,
    version_id      BIGINT       NOT NULL,
    rule_name       VARCHAR(50)  NOT NULL,
    priority        INTEGER      NOT NULL CHECK (priority > 0),
    input_type      VARCHAR(10)  NOT NULL
                    CHECK (input_type IN ('TEXT', 'COLOR')),
    input_value     VARCHAR(100) NOT NULL,
    item_name       VARCHAR(100) NOT NULL,
    chute_id        BIGINT       NOT NULL,

    UNIQUE (version_id, priority),
    UNIQUE (version_id, input_type, input_value),
    UNIQUE (organization_id, belt_id, version_id, id, chute_id),
    FOREIGN KEY (organization_id, belt_id, version_id, chute_id)
        REFERENCES version_chutes
            (organization_id, belt_id, version_id, chute_id)
);

