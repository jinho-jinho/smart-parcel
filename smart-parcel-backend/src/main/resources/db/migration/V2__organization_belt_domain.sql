-- 7. 배포 후 변경 금지
CREATE FUNCTION guard_rule_version_row()
RETURNS trigger LANGUAGE plpgsql SET search_path = parcel, public AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'DRAFT' THEN
            RAISE EXCEPTION '새 규칙 버전은 DRAFT로 생성해야 합니다';
        END IF;
        RETURN NEW;
    END IF;

    IF OLD.status = 'PUBLISHED' THEN
        RAISE EXCEPTION '배포된 규칙 버전은 변경하거나 삭제할 수 없습니다';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    IF NEW.status = 'PUBLISHED' THEN
        NEW.published_at := now();
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_guard_rule_version_row
BEFORE INSERT OR UPDATE OR DELETE ON rule_versions
FOR EACH ROW EXECUTE FUNCTION guard_rule_version_row();

CREATE FUNCTION guard_rule_version_child()
RETURNS trigger LANGUAGE plpgsql SET search_path = parcel, public AS $$
DECLARE
    version_status VARCHAR(12);
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        SELECT status INTO version_status
        FROM rule_versions
        WHERE id = OLD.version_id
        FOR SHARE;

        IF version_status = 'PUBLISHED' THEN
            RAISE EXCEPTION '배포된 버전의 규칙·슈트 설정은 변경할 수 없습니다';
        END IF;
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        SELECT status INTO version_status
        FROM rule_versions
        WHERE id = NEW.version_id
        FOR SHARE;

        IF version_status = 'PUBLISHED' THEN
            RAISE EXCEPTION '배포된 버전에 규칙·슈트 설정을 추가할 수 없습니다';
        END IF;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_guard_version_chutes
BEFORE INSERT OR UPDATE OR DELETE ON version_chutes
FOR EACH ROW EXECUTE FUNCTION guard_rule_version_child();

CREATE TRIGGER trg_guard_sorting_rules
BEFORE INSERT OR UPDATE OR DELETE ON sorting_rules
FOR EACH ROW EXECUTE FUNCTION guard_rule_version_child();

-- 벨트 지정·장비 적용·분류 시도에는 배포된 버전만 사용
CREATE FUNCTION assert_published_version(
    p_organization_id BIGINT,
    p_belt_id BIGINT,
    p_version_id BIGINT
)
RETURNS void LANGUAGE plpgsql SET search_path = parcel, public AS $$
DECLARE
    version_status VARCHAR(12);
BEGIN
    IF p_version_id IS NULL THEN
        RETURN;
    END IF;

    SELECT status INTO version_status
    FROM rule_versions
    WHERE organization_id = p_organization_id
      AND belt_id = p_belt_id
      AND id = p_version_id
    FOR SHARE;

    IF version_status IS DISTINCT FROM 'PUBLISHED' THEN
        RAISE EXCEPTION '배포된 규칙 버전만 지정할 수 있습니다';
    END IF;
END;
$$;

CREATE FUNCTION check_belt_desired_version()
RETURNS trigger LANGUAGE plpgsql SET search_path = parcel, public AS $$
BEGIN
    PERFORM assert_published_version(
        NEW.organization_id, NEW.id, NEW.desired_rule_version_id
    );
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_check_belt_desired_version
BEFORE UPDATE OF desired_rule_version_id ON conveyor_belts
FOR EACH ROW EXECUTE FUNCTION check_belt_desired_version();

CREATE FUNCTION check_device_applied_version()
RETURNS trigger LANGUAGE plpgsql SET search_path = parcel, public AS $$
